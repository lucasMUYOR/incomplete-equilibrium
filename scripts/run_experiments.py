"""Reproduce every number and figure of the README.

    python scripts/run_experiments.py            # ~2 minutes
    python scripts/run_experiments.py --quick    # smaller Monte Carlo
"""
from __future__ import annotations

import argparse
import os
import sys
import time
import warnings

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
from incomplete_equilibrium import (EquilibriumSolver, benchmarks as bm, example_market, montecarlo as mc,  # noqa: E402
                                    separable_market, separable_parts, spanned_market)

ROOT = os.path.join(os.path.dirname(__file__), "..")
FIG = os.path.join(ROOT, "figures")
OUT = os.path.join(ROOT, "results")


def main(quick: bool) -> None:
    warnings.filterwarnings("ignore", category=RuntimeWarning)  # overflow warnings precede a reported blow-up
    os.makedirs(FIG, exist_ok=True)
    os.makedirs(OUT, exist_ok=True)
    lines = ["# Results (generated by `scripts/run_experiments.py`)", ""]

    # ------------------------------------------------------------- benchmarks
    lines += ["## 1. Validation against closed forms", "",
              "| Case | Quantity | Numerical | Exact | Abs. error |", "|---|---|---|---|---|"]
    m = separable_market()
    s = EquilibriumSolver(m, N=121, M=400).solve()
    ex, lam = bm.separable_solution(separable_parts(), m.alphas, m.T, m.theta, 0, 0, 0)
    lines.append(f"| Separable (incomplete) | lambda(0,0,0) | {s.lambda_at_origin():.6f} | {lam:.6f} | {abs(s.lambda_at_origin()-lam):.1e} |")
    for i, a in enumerate(m.agents):
        lines.append(f"| Separable (incomplete) | CE agent {a.name} | {s.ce0()[i]:.6f} | {ex[i]:.6f} | {abs(s.ce0()[i]-ex[i]):.1e} |")
    m = spanned_market()
    s = EquilibriumSolver(m, N=121, M=400).solve()
    ys, lamf = bm.complete_market_solution([np.tanh, lambda x: -0.5 * np.sin(x)], m.alphas, m.T)
    lines.append(f"| Complete (Pareto) | lambda(0,0) | {s.lambda_at_origin():.6f} | {float(lamf(0.0)):.6f} | {abs(s.lambda_at_origin()-float(lamf(0.0))):.1e} |")
    for i, a in enumerate(m.agents):
        lines.append(f"| Complete (Pareto) | CE agent {a.name} | {s.ce0()[i]:.6f} | {ys[i]:.6f} | {abs(s.ce0()[i]-ys[i]):.1e} |")

    # ------------------------------------------------------------- main example
    m = example_market()
    t0 = time.time()
    sol = EquilibriumSolver(m, N=121, M=400).solve(store_path=True)
    lines += ["", "## 2. Non-separable incomplete market (3 agents)", "",
              f"Solve time (121x121 grid, 400 steps): {time.time()-t0:.1f} s", "",
              "### Grid convergence", "", "| N | M | lambda(0,0,0) | CE_A | CE_B | CE_C |", "|---|---|---|---|---|---|"]
    for N, M in [(61, 100), (121, 200), (121, 400), (241, 800), (241, 1600)]:
        s = EquilibriumSolver(m, N=N, M=M).solve()
        c = s.ce0()
        lines.append(f"| {N} | {M} | {s.lambda_at_origin():.6f} | {c[0]:.5f} | {c[1]:.5f} | {c[2]:.5f} |")

    n_paths = 50_000 if quick else 200_000
    r = mc.verify(sol, n_paths=n_paths, seed=1)
    aut = np.array([bm.autarky_ce(a.endowment, a.alpha, m.T) for a in m.agents])
    lines += ["", f"### Monte Carlo verification ({n_paths:,} paths)", "",
              "| Agent | alpha | PDE CE | MC CE (equilibrium) | MC no trade | MC 0.5x | MC 1.5x | Autarky (exact) |",
              "|---|---|---|---|---|---|---|---|"]
    for i, a in enumerate(m.agents):
        cells = [f"{r.ce[k][i]:.4f} ± {r.se[k][i]:.4f}" for k in ("equilibrium", "no_trade", "scaled_0.5", "scaled_1.5")]
        lines.append(f"| {a.name} | {a.alpha} | {sol.ce0()[i]:.4f} | " + " | ".join(cells) + f" | {aut[i]:.4f} |")
    lines += ["", f"Max market-clearing error |sum_i pi_i - theta| over all paths and dates: {r.max_clearing_error:.1e}"]

    # ------------------------------------------------------------- stress test
    lines += ["", "## 3. Stress test: scaling the endowments", "",
              "A scale is reported as *resolved* only if the certainty equivalents agree to 1% (relative to the "
              "endowment scale) across (a) grid refinement 121x121/400 -> 241x241/800 and (b) domain enlargement "
              "L = 6 -> 10. Otherwise the numerical method has reached its limit; this is **not** evidence that no "
              "equilibrium exists.", "",
              "| scale | scheme | lambda(0,0,0) | grid gap | domain gap | status |", "|---|---|---|---|---|---|"]
    for k in [0.5, 1, 2, 4, 8]:
        mk = example_market(scale=k)
        for scheme in ("central", "upwind"):
            try:
                a = EquilibriumSolver(mk, L=6, N=121, M=400, scheme=scheme).solve()
                b = EquilibriumSolver(mk, L=6, N=241, M=800, scheme=scheme).solve()
                c = EquilibriumSolver(mk, L=10, N=201, M=400, scheme=scheme).solve()
            except FloatingPointError:
                lines.append(f"| {k} | {scheme} | - | - | - | numerical blow-up |")
                continue
            g1 = float(np.max(np.abs(a.ce0() - b.ce0())))
            g2 = float(np.max(np.abs(a.ce0() - c.ce0())))
            ok = max(g1, g2) < 1e-2 * max(1.0, k)
            lines.append(f"| {k} | {scheme} | {b.lambda_at_origin():.4f} | {g1:.1e} | {g2:.1e} | "
                         f"{'resolved' if ok else 'not resolved'} |")

    # ------------------------------------------------------------- figures
    g = sol.grid
    fig, ax = plt.subplots(figsize=(6, 5))
    cs = ax.contourf(g, g, sol.lam0.T, levels=30, cmap="RdYlGn")
    fig.colorbar(cs, label=r"$\lambda(0,b,w)$")
    ax.set_xlabel("b (traded risk)"); ax.set_ylabel("w (unspanned risk)")
    ax.set_xlim(-3, 3); ax.set_ylim(-3, 3)
    ax.set_title("Equilibrium market price of risk at t = 0")
    fig.tight_layout(); fig.savefig(os.path.join(FIG, "lambda_surface.png"), dpi=150); plt.close(fig)

    lam0, yb0 = sol.fields(0)
    c = sol.center_index()
    fig, ax = plt.subplots(figsize=(7, 4))
    for i, a in enumerate(m.agents):
        ax.plot(g, lam0[:, c] / a.alpha - yb0[i][:, c], label=f"agent {a.name} (alpha={a.alpha})")
    ax.axhline(m.theta, color="k", lw=0.8, ls=":")
    ax.set_xlim(-3, 3); ax.set_xlabel("b  (w = 0)"); ax.set_ylabel("stock holding")
    ax.set_title("Equilibrium holdings at t = 0 (they sum to the supply)")
    ax.legend(); fig.tight_layout(); fig.savefig(os.path.join(FIG, "holdings.png"), dpi=150); plt.close(fig)

    ts, lam_t = [], []
    for n in range(0, len(sol.times) - 1, 10):
        lf, _ = sol.fields(n)
        ts.append(sol.times[n]); lam_t.append(lf[c, c])
    fig, ax = plt.subplots(figsize=(7, 4))
    ax.plot(ts, lam_t)
    ax.set_xlabel("t"); ax.set_ylabel(r"$\lambda(t,0,0)$"); ax.set_title("Market price of risk along b = w = 0")
    fig.tight_layout(); fig.savefig(os.path.join(FIG, "lambda_time.png"), dpi=150); plt.close(fig)

    with open(os.path.join(OUT, "summary.md"), "w") as f:
        f.write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    p = argparse.ArgumentParser()
    p.add_argument("--quick", action="store_true")
    main(p.parse_args().quick)
